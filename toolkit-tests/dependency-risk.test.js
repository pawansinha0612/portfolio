test('PyPI lookups and commands for each ecosystem', async () => {
  const log = [];
  const deps = D.parseRequirements('Django==3.2.0\n', 'requirements.txt');
  const sd = await D.scan(deps, async (url, init) => {
    log.push(url);
    if (/querybatch/.test(url)) return { ok: true, json: async () => ({ results: [{}] }) };
    return { ok: true, json: async () => ({ info: { version: '5.1.3', license: 'BSD-3-Clause', classifiers: [] }, releases: {} }) };
  });
  assert.deepStrictEqual(log, ['https://api.osv.dev/v1/querybatch', 'https://pypi.org/pypi/django/json']);
  const a = D.analyse(deps, sd);
  assert.strictEqual(a.rows[0].latest, '5.1.3');
  assert.strictEqual(a.plan[0].cmd, 'pip install "django==5.1.3"');
  const r = (eco, name, extra) => D.command(Object.assign({ ecosystem: eco, name, version: '1.0.0', direct: true }, extra), '1.2.3');
  assert.strictEqual(r('Go', 'golang.org/x/net'), 'go get golang.org/x/net@v1.2.3 && go mod tidy');
  assert.strictEqual(r('NuGet', 'Newtonsoft.Json'), 'dotnet add package Newtonsoft.Json --version 1.2.3');
  assert.strictEqual(r('Packagist', 'guzzlehttp/guzzle'), 'composer require guzzlehttp/guzzle:^1.2.3');
  assert.strictEqual(r('RubyGems', 'rack', { direct: false }), 'bundle update --conservative rack');
  assert.ok(/<version>1\.2\.3<\/version>/.test(r('Maven', 'org.x:y')));
});

