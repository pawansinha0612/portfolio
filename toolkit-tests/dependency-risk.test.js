function fakeFetch(log) {
  return async (url, init) => {
    log.push([url, init && init.body ? JSON.parse(init.body) : null]);
    const ok = body => ({ ok: true, status: 200, json: async () => JSON.parse(JSON.stringify(body)) });
    if (url === 'https://api.osv.dev/v1/querybatch') {
      const q = JSON.parse(init.body).queries;
      return ok({ results: q.map(x => { const ids = OSV_IDS[x.package.name + '@' + x.version]; return ids ? { vulns: ids.map(id => ({ id, modified: '2026-01-01T00:00:00Z' })) } : {}; }) });
    }
    let m = /^https:\/\/api\.osv\.dev\/v1\/vulns\/(.+)$/.exec(url);
    if (m) return ok(VULNS[decodeURIComponent(m[1])]);
    m = /^https:\/\/registry\.npmjs\.org\/(.+)\/([^/]+)$/.exec(url);
    if (m) { const n = decodeURIComponent(m[1]); const doc = NPM[n] && NPM[n][m[2]]; return doc ? ok(doc) : { ok: false, status: 404, json: async () => ({}) }; }
    return { ok: false, status: 500, json: async () => ({}) };
  };
}

